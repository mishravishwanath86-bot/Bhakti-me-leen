import json
import re
import sys

sys.stdout.reconfigure(encoding='utf-8')

with open('sundarkand_raw_pages.json', 'r', encoding='utf-8') as f:
    pages = json.load(f)

# Flatten sequential items
all_items = []
for p_num in range(1, 11):
    html = pages[str(p_num)]
    l_start = html.find('class="dpMiddleTitle"')
    next_div = html.find('class="dpFooter"', l_start)
    if next_div == -1:
        next_div = len(html)
    content = html[l_start:next_div]
    
    items = re.findall(r'(<h3[^>]*class="[^"]*dpLyricsType[^"]*"[^>]*>[\s\S]*?</h3>|<p[^>]*class="[^"]*dpGroup[^"]*"[^>]*>[\s\S]*?</p>)', content)
    for it in items:
        if '<h3' in it:
            heading = re.sub(r'<[^>]+>', '', it).strip()
            all_items.append(('heading', heading))
        else:
            lines = re.findall(r'<span class="dpRow">([\s\S]*?)</span>', it)
            clean_lines = [re.sub(r'<[^>]+>', '', l).strip() for l in lines]
            if clean_lines:
                all_items.append(('paragraph', clean_lines))

# Group into 60 dohas
dohas_raw = []
current_shloka = []
current_chaupais = []
current_chhand = []
current_sub_type = None

for typ, val in all_items:
    if typ == 'heading':
        if 'दोहा' in val:
            m = re.search(r'दोहा\s*(\d+)', val)
            num = int(m.group(1)) if m else len(dohas_raw) + 1
            current_sub_type = ('doha', num)
        elif 'चौपाई' in val:
            current_sub_type = 'chaupai'
        elif 'छन्द' in val:
            current_sub_type = 'chhand'
        elif 'श्लोक' in val:
            current_sub_type = 'shloka'
    else:
        if current_sub_type == 'shloka':
            current_shloka.extend(val)
        elif current_sub_type == 'chaupai':
            current_chaupais.extend(val)
        elif current_sub_type == 'chhand':
            current_chhand.extend(val)
        elif isinstance(current_sub_type, tuple) and current_sub_type[0] == 'doha':
            doha_num = current_sub_type[1]
            dohas_raw.append({
                'doha_number': doha_num,
                'shloka': current_shloka,
                'chaupais': current_chaupais,
                'chhand': current_chhand,
                'doha': val
            })
            current_shloka = []
            current_chaupais = []
            current_chhand = []
            current_sub_type = None

