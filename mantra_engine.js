// 3. Direct Reader Opening for a Mantra
window.readMantraItemDirect = function(deityKey, idx, initialMode) {
  const coll = window.MANTRA_COLLECTIONS ? window.MANTRA_COLLECTIONS[deityKey] : null;
  if (!coll || !coll.items || !coll.items[idx]) return;

  const item = coll.items[idx];
  window.closeMantraOptionsModal();

  const fullText = `॥ ${item.title} ॥\n\n${item.sanskrit}\n\n${item.english ? `[उच्चारण / Transliteration]\n${item.english}\n\n` : ''}॥ भावार्थ एवं माहात्म्य ॥\n${item.meaning || ''}\n\n${item.significance ? `॥ आध्यात्मिक महत्व ॥\n${item.significance}\n\n` : ''}${item.benefits ? `॥ जप फल ॥\n${item.benefits}\n\n` : ''}सनातन पंचांग प्रमाणिक वैदिक मन्त्र संग्रह।`;

  const readerObj = {
    id: item.id || `mantra_${deityKey}_${idx}`,
    title: item.title,
    deity: coll.deity,
    mantra: coll.mantra,
    text: fullText,
    type: 'mantra',
    meaning: item.meaning,
    english_lyrics: item.english,
    significance: item.significance,
    benefits: item.benefits,
    thumb: item.thumb || coll.img,
    img: coll.img,
    source: 'सनातन धर्म प्रामाणिक संग्रह',
    drik_url: coll.drik_url
  };

  if (typeof openReader === 'function') {
    openReader(readerObj, 'page-mantra');
  }

  // Load clean Vedic Sanskrit into AiBhaktiPlayer for divine recitation
  if (window.AiBhaktiPlayer) {
    window.AiBhaktiPlayer.loadContent({
      id: item.id || `mantra_${deityKey}_${idx}`,
      title: `${coll.deity} • ${item.title}`,
      text: item.sanskrit,
      type: 'mantra',
      deity: coll.deity
    });
  }
};

window.playMantraItemDirect = function(deityKey, idx) {
  window.readMantraItemDirect(deityKey, idx, 'audio');
  if (window.AiBhaktiPlayer) {
    window.AiBhaktiPlayer.togglePlay();
  }
};

// 4. Start 108 Jaap Mala Chanting
window.startMantraJaap = function(deityKey, idx) {
  const coll = window.MANTRA_COLLECTIONS ? window.MANTRA_COLLECTIONS[deityKey] : null;
  if (!coll || !coll.items || !coll.items[idx]) return;

  const item = coll.items[idx];
  window.closeMantraOptionsModal();

  const titleEl = document.getElementById('japa-mantra-title');
  const textEl = document.getElementById('japa-mantra-text');

  if (titleEl) titleEl.textContent = `${coll.deity} • ${item.title}`;
  if (textEl) textEl.textContent = item.sanskrit.split('\n')[0];

  if (typeof window.openJaapMalaModal === 'function') {
    window.openJaapMalaModal();
  } else {
    const jModal = document.getElementById('jaap-mala-modal');
    if (jModal) {
      jModal.style.display = 'flex';
      document.body.style.overflow = 'hidden';
    }
  }
};

// 5. Render Full Sanatan Panchang Mantra Page (page-mantra)
window._drikMantraCurrentFilter = 'all';
window._drikMantraCurrentSearch = '';

window.renderFullDrikMantraPage = function(filterCategory, searchQuery) {
  if (filterCategory !== undefined) window._drikMantraCurrentFilter = filterCategory;
  if (searchQuery !== undefined) window._drikMantraCurrentSearch = searchQuery.toLowerCase().trim();

  const container = document.getElementById('drik-mantra-cards-container');
  const pillsContainer = document.getElementById('drik-mantra-page-pills');
  if (!container) return;

  const categories = [
    ['all', '✨ सभी (105)'],
    ['gods', '🔱 देवताओं के वैदिक मन्त्र (59)'],
    ['goddesses', '🌸 देवियों के वैदिक मन्त्र (27)'],
    ['other', '🕊️ अन्य वैदिक मन्त्र (16)'],
    ['gayatri_mantras', '☀️ गायत्री मन्त्र (3)']
  ];

  if (pillsContainer && pillsContainer.children.length === 0) {
    pillsContainer.innerHTML = categories.map(([k, label]) => `
      <button class="drik-page-chip ${k === window._drikMantraCurrentFilter ? 'active' : ''}" data-cat="${k}" onclick="window.renderFullDrikMantraPage('${k}', window._drikMantraCurrentSearch)" style="padding:6px 14px; border-radius:16px; border:1px solid rgba(248,200,59,0.3); font-size:0.8rem; font-weight:800; cursor:pointer; white-space:nowrap; background:${k === window._drikMantraCurrentFilter ? 'linear-gradient(135deg, #F8C83B, #D97706)' : 'rgba(255,255,255,0.06)'}; color:${k === window._drikMantraCurrentFilter ? '#1A0B2E' : '#FDE68A'};">
        ${label}
      </button>
    `).join('');
  } else if (pillsContainer) {
    pillsContainer.querySelectorAll('.drik-page-chip').forEach(btn => {
      if (btn.getAttribute('data-cat') === window._drikMantraCurrentFilter) {
        btn.classList.add('active');
        btn.style.background = 'linear-gradient(135deg, #F8C83B, #D97706)';
        btn.style.color = '#1A0B2E';
      } else {
        btn.classList.remove('active');
        btn.style.background = 'rgba(255,255,255,0.06)';
        btn.style.color = '#FDE68A';
      }
    });
  }

  let html = '';
  const search = window._drikMantraCurrentSearch;
  const filter = window._drikMantraCurrentFilter;

  let totalMatched = 0;

  Object.keys(window.MANTRA_COLLECTIONS).forEach(catKey => {
    const coll = window.MANTRA_COLLECTIONS[catKey];
    if (!coll) return;

    // Filter by section
    if (filter !== 'all' && coll.section_key !== filter) {
      return;
    }

    let items = coll.items || [];

    // Filter by search
    if (search) {
      items = items.filter(i => 
        i.title.toLowerCase().includes(search) || 
        (i.title_en && i.title_en.toLowerCase().includes(search)) || 
        i.sanskrit.includes(search) ||
        (i.meaning && i.meaning.includes(search)) ||
        (i.benefits && i.benefits.includes(search)) ||
        coll.title.includes(search) ||
        coll.deity.includes(search)
      );
    }

    if (items.length > 0) {
      totalMatched += items.length;
      html += `
        <div style="margin-top:10px; margin-bottom:6px; display:flex; align-items:center; justify-content:space-between; border-bottom:1px solid rgba(248,200,59,0.2); padding-bottom:4px;">
          <div style="font-size:0.95rem; font-weight:900; color:#FDE68A; display:flex; align-items:center; gap:6px;">
            <img src="${coll.img}" onerror="this.src='${coll.fallbackImg}';" style="width:24px; height:24px; border-radius:50%; object-fit:cover; border:1px solid #F8C83B;" />
            <span>${coll.deity}</span>
            <span style="font-size:0.75rem; color:#A78BFA; font-weight:600;">(${coll.title})</span>
          </div>
          <span style="font-size:0.75rem; color:#FDE68A; background:rgba(248,200,59,0.15); padding:2px 8px; border-radius:10px; font-weight:800;">
            ${items.length} मन्त्र
          </span>
        </div>
      `;

      items.forEach((item, idx) => {
        html += window.renderDrikMantraCardHtml(item, catKey, coll, idx);
      });
    }
  });

  if (totalMatched === 0) {
    html = `
      <div style="text-align:center; padding:3rem 1rem; color:#9CA3AF;">
        <div style="font-size:2.5rem; margin-bottom:10px; opacity:0.6;">🕉️</div>
        <div style="font-size:1.05rem; font-weight:800; color:#FDE68A; margin-bottom:4px;">कोई मन्त्र नहीं मिला</div>
        <div style="font-size:0.85rem;">कृपया अन्य शब्द अथवा श्रेणी चुनकर पुनः प्रयास करें।</div>
      </div>
    `;
  }

  container.innerHTML = html;
};

