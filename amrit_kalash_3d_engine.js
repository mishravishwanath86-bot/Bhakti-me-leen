window.processAIVoiceText = function(text) {
  if (!text) return;

  window.stopListeningSpeechEngine();
  if (window.speechSynthesis) {
    try { window.speechSynthesis.cancel(); } catch(e) {}
  }

  const matched = window.matchVedicQuery(text);
  window.currentActiveGuidance = matched;

  // Sync with currentActiveShloka for Bhojpatra / Vault compatibility
  window.currentActiveShloka = {
    id: matched.id,
    source: matched.source,
    sanskrit: matched.sanskrit,
    hindiMeaning: matched.meaning,
    actionKarma: matched.remedies,
    opening: matched.opening,
    counsel: matched.counsel,
    userQuery: text
  };

  // Populate in Bhojpatra Modal elements as well
  const bSource = document.getElementById('bhojpatra-source-tag');
  const bSanskrit = document.getElementById('bhojpatra-sanskrit-text');
  const bHindi = document.getElementById('bhojpatra-hindi-meaning');
  const bAction = document.getElementById('bhojpatra-action-karma');
  if (bSource) bSource.textContent = matched.source;
  if (bSanskrit) bSanskrit.innerHTML = matched.sanskrit.replace(/\n/g, '<br>');
  if (bHindi) bHindi.textContent = matched.meaning;
  if (bAction) bAction.innerHTML = matched.remedies.replace(/\n/g, '<br>');

  // Switch modal stages
  const inputStage = document.getElementById('vedic-voice-input-stage');
  const guidanceStage = document.getElementById('vedic-voice-guidance-stage');

  if (inputStage) inputStage.style.display = 'none';
  if (guidanceStage) {
    guidanceStage.style.display = 'block';

    const qPill = document.getElementById('vedic-guidance-query-pill');
    const openingEl = document.getElementById('vedic-guidance-opening');
    const counselEl = document.getElementById('vedic-guidance-counsel');
    const sourceEl = document.getElementById('vedic-guidance-source');
    const shlokaEl = document.getElementById('vedic-guidance-shloka');
    const meaningEl = document.getElementById('vedic-guidance-meaning');
    const remediesEl = document.getElementById('vedic-guidance-remedies');
    const ttsBtn = document.getElementById('vedic-tts-toggle-btn');

    if (qPill) qPill.textContent = `आपकी मन की बात: "${text}"`;
    if (openingEl) openingEl.textContent = matched.opening;
    if (counselEl) counselEl.textContent = matched.counsel;
    if (sourceEl) sourceEl.textContent = matched.source;
    if (shlokaEl) shlokaEl.innerHTML = matched.sanskrit.replace(/\n/g, '<br>');
    if (meaningEl) meaningEl.textContent = matched.meaning;
    if (remediesEl) remediesEl.innerHTML = matched.remedies.replace(/\n/g, '<br>');

    if (ttsBtn) {
      ttsBtn.innerHTML = '<span>🔊</span> <span>दिव्य वाणी श्रवण करें (Audio)</span>';
      ttsBtn.style.background = 'linear-gradient(135deg, #F8C83B, #D97706)';
    }

    guidanceStage.scrollTop = 0;
  }

  if (typeof showToast === 'function') {
    showToast('🕉️ प्रभु का दिव्य मार्गदर्शन प्राप्त हुआ');
  }

  if (navigator.vibrate) navigator.vibrate([30, 50, 30]);
};

