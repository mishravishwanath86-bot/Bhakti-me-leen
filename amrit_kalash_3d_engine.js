window.saveCurrentShlokaToVault = function() {
  const guidance = window.currentActiveGuidance || window.currentActiveShloka;
  if (!guidance) return;

  let vault = [];
  try {
    const raw = localStorage.getItem('sanatan_saved_amrit_shlokas');
    vault = raw ? JSON.parse(raw) : [];
  } catch(e) {}

  if (!vault.some(item => item.id === guidance.id)) {
    vault.push({
      id: guidance.id,
      source: guidance.source,
      sanskrit: guidance.sanskrit,
      hindiMeaning: guidance.meaning || guidance.hindiMeaning,
      actionKarma: guidance.remedies || guidance.actionKarma,
      counsel: guidance.counsel || '',
      savedAt: new Date().toLocaleDateString('hi-IN')
    });
    localStorage.setItem('sanatan_saved_amrit_shlokas', JSON.stringify(vault));
    if (typeof showToast === 'function') {
      showToast('💾 श्लोक व दिव्य सलाह अमृत संग्रह में सहेजी गई!');
    }
  } else {
    if (typeof showToast === 'function') {
      showToast('✓ यह श्लोक पहले से ही संग्रह में मौजूद है');
    }
  }
};

