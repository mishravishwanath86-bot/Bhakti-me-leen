window.isTTSPlaying = false;

window.toggleAIVoiceSpeechRecitation = function() {
  if (!window.speechSynthesis) {
    if (typeof showToast === 'function') showToast('💡 इस डिवाइस पर ऑडियो वाचन समर्थित नहीं है');
    return;
  }

  const ttsBtn = document.getElementById('vedic-tts-toggle-btn');

  if (window.speechSynthesis.speaking) {
    window.speechSynthesis.cancel();
    window.isTTSPlaying = false;
    if (ttsBtn) {
      ttsBtn.innerHTML = '<span>🔊</span> <span>दिव्य वाणी श्रवण करें (Audio)</span>';
      ttsBtn.style.background = 'linear-gradient(135deg, #F8C83B, #D97706)';
    }
    return;
  }

  const guidance = window.currentActiveGuidance;
  if (!guidance) return;

  try {
    window.speechSynthesis.cancel();

    // Clean spoken text: Opening + Counsel + Shloka + Meaning + Remedies
    const textToSpeak = `${guidance.opening}। ${guidance.counsel}। ${guidance.source}। ${guidance.sanskrit}। भावार्थ: ${guidance.meaning}। आज का संकल्प: ${guidance.remedies}`;
    const cleanText = textToSpeak.replace(/[*#_\n]/g, ' ').replace(/१\.|२\.|३\./g, ' ');

    const utterance = new SpeechSynthesisUtterance(cleanText);
    utterance.lang = 'hi-IN';
    utterance.rate = 0.88;
    utterance.pitch = 1.05;

    utterance.onstart = function() {
      window.isTTSPlaying = true;
      if (ttsBtn) {
        ttsBtn.innerHTML = '<span style="animation:pulseGlow 1s infinite;">⏸️</span> <span>वाणी रोकें (Pause)</span>';
        ttsBtn.style.background = 'linear-gradient(135deg, #10B981, #059669)';
      }
      if (typeof showToast === 'function') showToast('🔊 दिव्य वाणी का श्रवण करें...');
    };

    utterance.onend = function() {
      window.isTTSPlaying = false;
      if (ttsBtn) {
        ttsBtn.innerHTML = '<span>🔊</span> <span>दिव्य वाणी श्रवण करें (Audio)</span>';
        ttsBtn.style.background = 'linear-gradient(135deg, #F8C83B, #D97706)';
      }
    };

    utterance.onerror = function() {
      window.isTTSPlaying = false;
      if (ttsBtn) {
        ttsBtn.innerHTML = '<span>🔊</span> <span>दिव्य वाणी श्रवण करें (Audio)</span>';
        ttsBtn.style.background = 'linear-gradient(135deg, #F8C83B, #D97706)';
      }
    };

    window.speechSynthesis.speak(utterance);
  } catch(e) {
    console.warn("TTS speak error:", e);
  }
};

