window.matchVedicQuery = function(query) {
  const q = (query || '').toLowerCase().trim();
  if (!q) return window.VEDIC_GUIDANCE_DB.anxious_future;

  let bestMatch = null;
  let bestScore = -1;

  for (const key in window.VEDIC_GUIDANCE_DB) {
    const item = window.VEDIC_GUIDANCE_DB[key];
    let score = 0;

    for (const kw of item.keywords) {
      const lowerKw = kw.toLowerCase();
      if (q === lowerKw) {
        score += 50;
      } else if (q.includes(lowerKw)) {
        score += lowerKw.length * 4; // Longer, specific multi-word matches take precedence
      }
    }

    if (score > bestScore) {
      bestScore = score;
      bestMatch = item;
    }
  }

  return (bestScore > 0 && bestMatch) ? bestMatch : window.VEDIC_GUIDANCE_DB.anxious_future;
};

